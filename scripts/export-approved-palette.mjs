// P-TOKEN-01. Vanilla Node build utility; no browser code, no runtime CSS import.
// Authority: decisions.json > VIS-002.approvedPalette (reference only, NOT product mapping).
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const SOURCE_GIT_BLOB = "63b60f8d87327c6fd1e80c8cdf4ff832c4089bfa";
export const EXPORT_VERSION = "0.1.0";
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ROLES = Object.freeze(["canvas", "surface", "surfaceSoft", "textPrimary", "textSecondary", "border", "focusOutline"]);
const THEMES = Object.freeze(["light", "dark"]);
const toKebab = value => value.replace(/[A-Z]/g, letter => "-" + letter.toLowerCase());

export function gitBlobSha(content) {
  const hash = createHash("sha1");
  hash.update("blob " + Buffer.byteLength(content, "utf8") + "\0");
  hash.update(content, "utf8");
  return hash.digest("hex");
}

export function derive(source) {
  assert.equal(gitBlobSha(source), SOURCE_GIT_BLOB,
    "VIS-002 source changed: stop export and review homologation/provenance before updating version");
  const document = JSON.parse(source);
  const decision = document.decisions?.find(item => item.id === "VIS-002");
  assert.ok(decision, "VIS-002 not found");
  assert.equal(decision.verdict, "agreed");
  assert.equal(decision.implementationAuthorized, false,
    "VIS-002 mapping status changed: re-evaluate product integration gate separately");
  assert.match(decision.approvedPalette?.status || "", /approved-for-design-system-palette/);
  const palette = decision.approvedPalette, colors = palette.colors;
  assert.deepEqual(Object.keys(colors).sort(), [...ROLES].sort(),
    "palette changed: this version must explicitly recognize new/removed roles");
  const entries = [];
  for (const role of ROLES) {
    for (const theme of THEMES) {
      const value = colors[role]?.[theme];
      assert.match(value || "", /^#[0-9a-fA-F]{6}$/, role + "." + theme + ": expected opaque hex color");
      entries.push({
        cssName: "--ds-reference-" + toKebab(role) + "-" + theme,
        role, theme, value: value.toUpperCase(),
        sourcePath: "VIS-002.approvedPalette.colors." + role + "." + theme
      });
    }
  }
  const width = palette.focusTreatment?.outlineWidthCssPx;
  const offset = palette.focusTreatment?.offsetCssPx;
  assert.equal(width, 4, "review focus reference revision before export");
  assert.equal(offset, 3, "review focus reference revision before export");
  for (const [key,value] of [["focus-outline-width",width],["focus-outline-offset",offset]]) {
    entries.push({
      cssName: "--ds-reference-" + key, role: key, theme: "both",
      value: value + "px", sourcePath: "VIS-002.approvedPalette.focusTreatment"
    });
  }
  return { entries, authority: {
    decisionId: "VIS-002", decisionStatus: decision.status,
    approvalSource: palette.approvalSource, scope: palette.scope,
    implementationAuthorized: false
  }};
}

export function buildArtifacts(source) {
  const { entries, authority } = derive(source);
  const header = [
    "/* GENERATED by scripts/export-approved-palette.mjs; DO NOT EDIT.",
    " * source: decisions.json VIS-002 / git-blob " + SOURCE_GIT_BLOB,
    " * Reference-only names, NOT mapped to product CSS roles.",
    " * DO NOT LINK into app pages until approved component/route mapping,",
    " * computed-style equivalence and explicit product integration PR.",
    " */"
  ];
  const css = [...header, ":root {",
    ...entries.map(x => "  " + x.cssName + ": " + x.value + ";"),
    "}", ""].join("\n");
  const manifest = {
    schema: "M2DDesignSystemReferenceTokens/0.1",
    version: EXPORT_VERSION,
    source: { repository: "EAKerber/MobiliPresenter2D_DesignSystem",
      path: "decisions.json", gitBlobSha: SOURCE_GIT_BLOB },
    authority,
    policy: {
      sourceOfTruth: "VIS-002.approvedPalette",
      productIntegration: "HOLD — not authorized by VIS-002",
      generatedCssMayBeLinkedAtRuntime: false,
      noSemanticAliasesForComponents: true,
      noGlobalStateColors: true
    },
    entries
  };
  return { css, manifest: JSON.stringify(manifest, null, 2) + "\n" };
}

export async function exportPalette({ sourceFile = join(ROOT, "decisions.json"),
  outDir = join(ROOT, "dist"), check = false } = {}) {
  const source = await readFile(sourceFile, "utf8");
  const { css, manifest } = buildArtifacts(source);
  const targets = [
    [join(outDir, "approved-palette-reference.css"), css],
    [join(outDir, "approved-palette-reference.manifest.json"), manifest]
  ];
  for (const [target, expected] of targets) {
    if (check) {
      const current = await readFile(target, "utf8");
      assert.equal(current, expected, target + " is stale / manually changed");
    } else {
      await mkdir(dirname(target), { recursive: true });
      await writeFile(target, expected, "utf8");
    }
  }
  return targets.map(([target]) => target);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const outArg = process.argv.find(arg => arg.startsWith("--out-dir="));
  const invalidArgs = process.argv.slice(2).filter(arg => arg !== "--check" && !arg.startsWith("--out-dir="));
  if (invalidArgs.length) throw new Error("unknown arguments: " + invalidArgs.join(", "));
  const outDir = outArg ? resolve(outArg.slice("--out-dir=".length)) : undefined;
  exportPalette({ check, ...(outDir ? {outDir} : {}) }).then(targets => {
    console.log("P_TOKEN_01_" + (check ? "CHECK" : "EXPORT") + "_PASS " + targets.join(" "));
  }).catch(error => { console.error(error); process.exitCode = 1; });
}
